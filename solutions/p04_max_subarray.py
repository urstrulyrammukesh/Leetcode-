"""Maximum Subarray (Kadane's algorithm): largest sum of a contiguous subarray. O(n)."""

def max_subarray(nums):
    best = cur = nums[0]
    for x in nums[1:]:
        cur = max(x, cur + x)
        best = max(best, cur)
    return best

if __name__ == "__main__":
    assert max_subarray([-2, 1, -3, 4, -1, 2, 1, -5, 4]) == 6
    assert max_subarray([-3, -1, -2]) == -1
    assert max_subarray([5]) == 5
    print("p04 ok")
